        private static void WriteHeader(IXLWorksheet ws, string reportTitle)
        {
            ws.Cell(1, 1).Value = CompanyName;
            ws.Cell(1, 1).Style.Font.Bold      = true;
            ws.Cell(1, 1).Style.Font.FontSize  = 18;
            ws.Cell(1, 1).Style.Font.FontColor = XLColor.FromHtml("#1a3c5e");
            ws.Range(1, 1, 1, 6).Merge();

            ws.Cell(2, 1).Value = CompanyAddress;
            ws.Cell(2, 1).Style.Font.Italic   = true;
            ws.Cell(2, 1).Style.Font.FontSize = 10;
            ws.Range(2, 1, 2, 6).Merge();

            ws.Cell(3, 1).Value = reportTitle;
            ws.Cell(3, 1).Style.Font.Bold      = true;
            ws.Cell(3, 1).Style.Font.FontSize  = 13;
            ws.Cell(3, 1).Style.Font.FontColor = XLColor.FromHtml("#2e6da4");
            ws.Range(3, 1, 3, 6).Merge();

            ws.Cell(4, 1).Value =
                $"Generated: {DateTime.Now:MMMM dd, yyyy HH:mm}   |   " +
                $"Generated by: {SessionHelper.FullName}";
            ws.Cell(4, 1).Style.Font.FontSize = 9;
            ws.Cell(4, 1).Style.Font.Italic   = true;
            ws.Range(4, 1, 4, 6).Merge();

            var logo = ws.Range(1, 7, 4, 8);
            logo.Merge();
            logo.FirstCell().Value = "[LIBRARY LOGO]";
            logo.Style.Alignment.Horizontal = XLAlignmentHorizontalValues.Center;
            logo.Style.Alignment.Vertical   = XLAlignmentVerticalValues.Center;
            logo.Style.Border.OutsideBorder = XLBorderStyleValues.Thin;
            logo.Style.Font.Italic          = true;
            logo.Style.Font.FontColor       = XLColor.Gray;

            ws.Row(5).Height = 6;
        }

        private static void WriteSignatureBlock(IXLWorksheet ws, int startRow, int cols)
        {
            startRow += 3;

            ws.Cell(startRow,     1).Value = "Prepared by:";
            ws.Cell(startRow + 1, 1).Value = SessionHelper.FullName;
            ws.Cell(startRow + 1, 1).Style.Font.Bold = true;
            ws.Cell(startRow + 2, 1).Value = $"({SessionHelper.Role})";

            ws.Range(startRow + 3, 1, startRow + 3, 3)
              .Style.Border.BottomBorder = XLBorderStyleValues.Thin;

            ws.Cell(startRow + 4, 1).Value = "Signature over Printed Name";
            ws.Cell(startRow + 4, 1).Style.Font.Italic   = true;
            ws.Cell(startRow + 4, 1).Style.Font.FontSize = 9;

            int col = Math.Max(1, cols - 1);
            ws.Cell(startRow,     col).Value = "Noted/Approved by:";
            ws.Cell(startRow + 1, col).Value = "_________________________";
            ws.Cell(startRow + 2, col).Value = "(Library Director)";
            ws.Cell(startRow + 2, col).Style.Font.Italic = true;
        }

        private static void StyleDataTable(IXLWorksheet ws, int hdrRow, int lastCol, int lastDataRow)
        {
            var hdr = ws.Range(hdrRow, 1, hdrRow, lastCol);
            hdr.Style.Fill.BackgroundColor = XLColor.FromHtml("#1a3c5e");
            hdr.Style.Font.FontColor       = XLColor.White;
            hdr.Style.Font.Bold            = true;
            hdr.Style.Alignment.Horizontal = XLAlignmentHorizontalValues.Center;

            for (int r = hdrRow + 1; r <= lastDataRow; r++)
                if ((r - hdrRow) % 2 == 0)
                    ws.Range(r, 1, r, lastCol).Style.Fill.BackgroundColor =
                        XLColor.FromHtml("#eaf1fb");

            ws.Range(hdrRow, 1, lastDataRow, lastCol)
              .Style.Border.OutsideBorder = XLBorderStyleValues.Medium;
            ws.Range(hdrRow, 1, lastDataRow, lastCol)
              .Style.Border.InsideBorder  = XLBorderStyleValues.Hair;
        }

