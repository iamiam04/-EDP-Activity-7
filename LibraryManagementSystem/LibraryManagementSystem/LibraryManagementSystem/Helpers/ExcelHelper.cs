        public static string GenerateBorrowingsReport(System.Data.DataTable dt, string savePath)
        {
            ChartInfo chartInfo;

            using (var wb = new XLWorkbook())
            {
                var ws = wb.AddWorksheet("Borrowings Report");
                WriteHeader(ws, "Borrowings Transaction Report");

                int hdrRow = 6;
                string[] cols = { "Borrowing ID", "Book Title", "Borrower", "Borrow Date", "Due Date", "Return Date", "Fine (PHP)" };
                for (int c = 0; c < cols.Length; c++)
                    ws.Cell(hdrRow, c + 1).Value = cols[c];

                int dataRow = hdrRow + 1;
                foreach (DataRow row in dt.Rows)
                {
                    ws.Cell(dataRow, 1).Value = row["borrowing_id"]?.ToString();
                    ws.Cell(dataRow, 2).Value = row["title"]?.ToString();
                    ws.Cell(dataRow, 3).Value = row["borrower"]?.ToString();
                    ws.Cell(dataRow, 4).Value = row["borrow_date"]?.ToString();
                    ws.Cell(dataRow, 5).Value = row["due_date"]?.ToString();
                    ws.Cell(dataRow, 6).Value = string.IsNullOrEmpty(row["return_date"]?.ToString())
                        ? "Not Returned" : row["return_date"]!.ToString();
                    ws.Cell(dataRow, 7).Value = Convert.ToDecimal(row["fine_amount"] ?? 0);
                    ws.Cell(dataRow, 7).Style.NumberFormat.Format = "#,##0.00";
                    dataRow++;
                }

                int lastData = dataRow - 1;
                StyleDataTable(ws, hdrRow, cols.Length, lastData);
                ws.Cell(lastData + 1, 6).Value    = "Total Fine:";
                ws.Cell(lastData + 1, 6).Style.Font.Bold = true;
                ws.Cell(lastData + 1, 7).FormulaA1 = $"=SUM(G{hdrRow + 1}:G{lastData})";
                ws.Cell(lastData + 1, 7).Style.NumberFormat.Format = "#,##0.00";
                ws.Cell(lastData + 1, 7).Style.Font.Bold = true;
                ws.Columns().AdjustToContents();
                WriteSignatureBlock(ws, lastData + 1, cols.Length);

                chartInfo = AddChartDataSheet(wb, "Borrowings Chart",
                    "Fine Amounts per Borrower",
                    new[] { "Fine (PHP)" },
                    dt,
                    row => (row["borrower"]?.ToString() ?? "",
                            new[] { Convert.ToDouble(row["fine_amount"] ?? 0) }));

                wb.SaveAs(savePath);
            }

            InjectChart(savePath, chartInfo);
            return savePath;
        }

        // ════════════════════════════════════════════════════════════════════
        //  2. BOOKS INVENTORY REPORT
        // ════════════════════════════════════════════════════════════════════

        public static string GenerateBooksReport(System.Data.DataTable dt, string savePath)
        {
            ChartInfo chartInfo;

            using (var wb = new XLWorkbook())
            {
                var ws = wb.AddWorksheet("Books Inventory");
                WriteHeader(ws, "Books Inventory Report");

                int hdrRow = 6;
                string[] cols = { "Book ID", "Title", "Author", "ISBN", "Total Copies", "Available", "Borrowed" };
                for (int c = 0; c < cols.Length; c++)
                    ws.Cell(hdrRow, c + 1).Value = cols[c];

                int dataRow = hdrRow + 1;
                foreach (DataRow row in dt.Rows)
                {
                    int total     = Convert.ToInt32(row["total_copies"]     ?? 0);
                    int available = Convert.ToInt32(row["available_copies"] ?? 0);
                    ws.Cell(dataRow, 1).Value = row["book_id"]?.ToString();
                    ws.Cell(dataRow, 2).Value = row["title"]?.ToString();
                    ws.Cell(dataRow, 3).Value = row["author"]?.ToString();
                    ws.Cell(dataRow, 4).Value = row["isbn"]?.ToString();
                    ws.Cell(dataRow, 5).Value = total;
                    ws.Cell(dataRow, 6).Value = available;
                    ws.Cell(dataRow, 7).Value = total - available;
                    dataRow++;
                }

                int lastData = dataRow - 1;
                StyleDataTable(ws, hdrRow, cols.Length, lastData);
                ws.Columns().AdjustToContents();
                WriteSignatureBlock(ws, lastData + 1, cols.Length);

                chartInfo = AddChartDataSheet(wb, "Inventory Chart",
                    "Book Inventory: Available vs Borrowed",
                    new[] { "Available", "Borrowed" },
                    dt,
                    row =>
                    {
                        int tot = Convert.ToInt32(row["total_copies"]     ?? 0);
                        int avl = Convert.ToInt32(row["available_copies"] ?? 0);
                        return (row["title"]?.ToString() ?? "",
                                new[] { (double)avl, (double)(tot - avl) });
                    });

                wb.SaveAs(savePath);
            }

            InjectChart(savePath, chartInfo);
            return savePath;
        }

