        // ════════════════════════════════════════════════════════════════════
        //  CHART DATA SHEET  (ClosedXML pass – writes Sheet 2 data rows)
        // ════════════════════════════════════════════════════════════════════

        private static ChartInfo AddChartDataSheet(
            XLWorkbook wb,
            string sheetName,
            string chartTitle,
            string[] seriesNames,
            System.Data.DataTable dt,
            Func<DataRow, (string label, double[] vals)> mapper)
        {
            var ws2 = wb.AddWorksheet(sheetName);

            ws2.Cell(1, 1).Value    = "Label";
            ws2.Cell(1, 1).Style.Font.Bold = true;
            for (int s = 0; s < seriesNames.Length; s++)
            {
                ws2.Cell(1, s + 2).Value    = seriesNames[s];
                ws2.Cell(1, s + 2).Style.Font.Bold = true;
            }

            var cats   = new List<string>();
            var values = Enumerable.Range(0, seriesNames.Length)
                                   .Select(_ => new List<double>())
                                   .ToArray();

            int r = 2;
            foreach (DataRow row in dt.Rows)
            {
                var (label, vals) = mapper(row);
                cats.Add(label);
                ws2.Cell(r, 1).Value = label;
                for (int s = 0; s < Math.Min(vals.Length, seriesNames.Length); s++)
                {
                    ws2.Cell(r, s + 2).Value = vals[s];
                    values[s].Add(vals[s]);
                }
                r++;
            }

            ws2.Columns().AdjustToContents();

            return new ChartInfo(
                sheetName,
                chartTitle,
                seriesNames,
                cats.ToArray(),
                values.Select(v => v.ToArray()).ToArray());
        }

        // ════════════════════════════════════════════════════════════════════
        //  OPENXML CHART INJECTION  (re-opens the .xlsx and injects DrawingML)
        // ════════════════════════════════════════════════════════════════════

        private static void InjectChart(string filePath, ChartInfo info)
        {
            if (info.Categories.Length == 0) return;

            using var doc  = SpreadsheetDocument.Open(filePath, isEditable: true);
            var wbPart     = doc.WorkbookPart!;

            var sheetEntry = wbPart.Workbook
                .Descendants<Sheet>()
                .FirstOrDefault(s => s.Name?.Value == info.SheetName);
            if (sheetEntry?.Id?.Value is null) return;

            var wsPart = (WorksheetPart)wbPart.GetPartById(sheetEntry.Id.Value);

            // ChartPart lives inside DrawingsPart
            var drawingsPart = wsPart.AddNewPart<DrawingsPart>();
            var chartPart    = drawingsPart.AddNewPart<ChartPart>();

            chartPart.ChartSpace = BuildBarChartSpace(info);
            chartPart.ChartSpace.Save();

            string chartRelId = drawingsPart.GetIdOfPart(chartPart);

            drawingsPart.WorksheetDrawing = BuildWorksheetDrawing(chartRelId);
            drawingsPart.WorksheetDrawing.Save();

            string drawingsRelId = wsPart.GetIdOfPart(drawingsPart);
            wsPart.Worksheet.Append(
                new DocumentFormat.OpenXml.Spreadsheet.Drawing { Id = drawingsRelId });
            wsPart.Worksheet.Save();
        }

        // ── DrawingML bar chart ──────────────────────────────────────────────

        private static C.ChartSpace BuildBarChartSpace(ChartInfo info)
        {
            var cs = new C.ChartSpace();
            cs.Append(new C.EditingLanguage { Val = "en-US" });

            var chart = new C.Chart();
            chart.Append(new C.AutoTitleDeleted { Val = false });
            chart.Append(MakeTitle(info.Title));

            var plotArea = new C.PlotArea();
            plotArea.Append(new C.Layout());

            var barChart = new C.BarChart();
            barChart.Append(new C.BarDirection { Val = C.BarDirectionValues.Column });
            barChart.Append(new C.BarGrouping  { Val = C.BarGroupingValues.Clustered });
            barChart.Append(new C.VaryColors   { Val = false });

            uint[] palette = { 0x1A3C5Eu, 0x2E86C1u, 0x28B463u, 0xE67E22u, 0x8E44ADu };

            for (int s = 0; s < info.SeriesNames.Length; s++)
            {
                var ser = new C.BarChartSeries();
                ser.Append(new C.Index { Val = (uint)s });
                ser.Append(new C.Order { Val = (uint)s });
                ser.Append(MakeSeriesText(info.SeriesNames[s]));
                ser.Append(MakeShapeProperties(palette[s % palette.Length]));
                ser.Append(MakeCategoryAxisData(info.Categories));
                ser.Append(MakeValues(info.Values[s]));
                barChart.Append(ser);
            }

            barChart.Append(new C.AxisId { Val = 100u });
            barChart.Append(new C.AxisId { Val = 200u });
            plotArea.Append(barChart);

            var catAxis = new C.CategoryAxis();
            catAxis.Append(new C.AxisId    { Val = 100u });
            catAxis.Append(new C.Scaling(new C.Orientation { Val = C.OrientationValues.MinMax }));
            catAxis.Append(new C.Delete    { Val = false });
            catAxis.Append(new C.AxisPosition { Val = C.AxisPositionValues.Bottom });
            catAxis.Append(new C.CrossingAxis  { Val = 200u });
            plotArea.Append(catAxis);

            var valAxis = new C.ValueAxis();
            valAxis.Append(new C.AxisId    { Val = 200u });
            valAxis.Append(new C.Scaling(new C.Orientation { Val = C.OrientationValues.MinMax }));
            valAxis.Append(new C.Delete    { Val = false });
            valAxis.Append(new C.AxisPosition { Val = C.AxisPositionValues.Left });
            valAxis.Append(new C.CrossingAxis  { Val = 100u });
            plotArea.Append(valAxis);

            chart.Append(plotArea);
            chart.Append(new C.Legend(new C.LegendPosition { Val = C.LegendPositionValues.Bottom }));
            chart.Append(new C.PlotVisibleOnly { Val = true });

            cs.Append(chart);
            return cs;
        }

        private static C.Title MakeTitle(string text)
        {
            var run = new A.Run();
            run.Append(new A.RunProperties { Language = "en-US", Bold = true });
            run.Append(new A.Text(text));

            var para = new A.Paragraph();
            para.Append(run);

            var rich = new C.RichText();
            rich.Append(new A.BodyProperties());
            rich.Append(new A.ListStyle());
            rich.Append(para);

            var tx = new C.ChartText();
            tx.Append(rich);

            var title = new C.Title();
            title.Append(tx);
            title.Append(new C.Overlay { Val = false });
            return title;
        }

        private static C.SeriesText MakeSeriesText(string name)
        {
            var cache = new C.StringCache();
            cache.Append(new C.PointCount { Val = 1u });
            cache.Append(new C.StringPoint { Index = 0u, NumericValue = new C.NumericValue(name) });

            var strRef = new C.StringReference();
            strRef.Append(new C.Formula($"\"{name}\""));
            strRef.Append(cache);

            var tx = new C.SeriesText();
            tx.Append(strRef);
            return tx;
        }

        private static C.ShapeProperties MakeShapeProperties(uint rgbHex)
        {
            var solidFill = new A.SolidFill();
            solidFill.Append(new A.RgbColorModelHex { Val = rgbHex.ToString("X6") });

            var spPr = new C.ShapeProperties();
            spPr.Append(solidFill);
            return spPr;
        }

        private static C.CategoryAxisData MakeCategoryAxisData(string[] cats)
        {
            var cache = new C.StringCache();
            cache.Append(new C.PointCount { Val = (uint)cats.Length });
            for (int i = 0; i < cats.Length; i++)
                cache.Append(new C.StringPoint
                {
                    Index        = (uint)i,
                    NumericValue = new C.NumericValue(cats[i])
                });

            var strRef = new C.StringReference();
            strRef.Append(new C.Formula("Sheet2!$A$2:$A$" + (cats.Length + 1)));
            strRef.Append(cache);

            var axData = new C.CategoryAxisData();
            axData.Append(strRef);
            return axData;
        }

        private static C.Values MakeValues(double[] vals)
        {
            var cache = new C.NumberingCache();
            cache.Append(new C.FormatCode("General"));
            cache.Append(new C.PointCount { Val = (uint)vals.Length });
            for (int i = 0; i < vals.Length; i++)
                cache.Append(new C.NumericPoint
                {
                    Index        = (uint)i,
                    NumericValue = new C.NumericValue(vals[i].ToString("G"))
                });

            var numRef = new C.NumberReference();
            numRef.Append(new C.Formula("Sheet2!$B$2:$B$" + (vals.Length + 1)));
            numRef.Append(cache);

            var v = new C.Values();
            v.Append(numRef);
            return v;
        }

        // ── Worksheet drawing (anchors chart on the sheet) ───────────────────

        private static XDr.WorksheetDrawing BuildWorksheetDrawing(string chartRelId)
        {
            var anchor = new XDr.TwoCellAnchor();

            anchor.Append(new XDr.FromMarker(
                new XDr.ColumnId("0"),  new XDr.ColumnOffset("0"),
                new XDr.RowId("3"),    new XDr.RowOffset("0")));
            anchor.Append(new XDr.ToMarker(
                new XDr.ColumnId("10"), new XDr.ColumnOffset("0"),
                new XDr.RowId("25"),   new XDr.RowOffset("0")));

            var nvProps = new XDr.NonVisualGraphicFrameProperties(
                new XDr.NonVisualDrawingProperties { Id = 2u, Name = "Chart 1" },
                new XDr.NonVisualGraphicFrameDrawingProperties());

            var xfrm = new XDr.Transform(
                new A.Offset  { X = 0L, Y = 0L },
                new A.Extents { Cx = 0L, Cy = 0L });

            var graphicData = new A.GraphicData
            {
                Uri = "http://schemas.openxmlformats.org/drawingml/2006/chart"
            };
            graphicData.Append(new C.ChartReference { Id = chartRelId });

            var graphic = new A.Graphic();
            graphic.Append(graphicData);

            var frame = new XDr.GraphicFrame();
            frame.Append(nvProps);
            frame.Append(xfrm);
            frame.Append(graphic);

            anchor.Append(frame);
            anchor.Append(new XDr.ClientData());

            var wd = new XDr.WorksheetDrawing();
            wd.Append(anchor);
            return wd;
        }
